// Location in overall maze. Not limited to within one chunk
struct MazeLocation {
	int x;
	int y;

	bool operator == (const MazeLocation& loc) const
	{
		return (x == loc.x && y == loc.y);
	}

	bool operator < (const MazeLocation& loc) const
	{
		return (x < loc.x) || ((x == loc.x) && (y < loc.y));
	}
};

